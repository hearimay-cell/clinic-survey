# 프리셋 묶음 (카톡 링크 발송 시 원클릭 선택용)
SURVEY_PRESETS = {
    "초진 기본 심리세트 (BAI+PHQ9+ISI)": ["BAI", "PHQ9", "ISI"],
    "불안·공황 집중세트 (BAI+PDI+GAD7+ISI)": ["BAI", "PDI", "GAD7", "ISI"],
    "성인 초진 종합 (BAI+PHQ9+PDI+ISI+한방문진)": ["BAI", "PHQ9", "PDI", "ISI", "HANBANG"],
    "소아·청소년 틱 세트 (틱초진+YGTSS+ADHD)": ["TIC_INIT", "YGTSS", "ADHD"],
    "ADHD 단독 (코너스 ADHD설문)": ["ADHD"],
    "우울·불안·불면 (PHQ9+GAD7+ISI)": ["PHQ9", "GAD7", "ISI"],
    "한방진단검사지 단독": ["HANBANG"],
}


def evaluate_survey_response(survey_code: str, answers: Any, meta_answers: Dict[str, Any] = None) -> Dict[str, Any]:
    """
    개별 설문지의 응답 배열(answers)을 받아 총점, 중증도, 주의 문항, 소척도 요약을 계산합니다.
    """
    spec = SURVEY_CATALOG.get(survey_code)
    if not spec:
        return {
            "survey_code": survey_code,
            "title": survey_code,
            "total_score": 0,
            "max_score": 0,
            "severity": "미분류",
            "color": "#6b7280",
            "alerts": [],
            "answers": answers,
        }

    # 체크리스트형 설문 (TIC_INIT, HANBANG)
    if spec.get("is_checklist"):
        checked_sections = answers if isinstance(answers, dict) else {}
        total_checked = 0
        alerts = []
        section_summaries = []
        for sec in spec.get("sections", []):
            sec_id = sec["id"]
            items_checked = checked_sections.get(sec_id, [])
            other_text = checked_sections.get(f"{sec_id}_other", "")
            count = len(items_checked) + (1 if other_text else 0)
            total_checked += count
            if items_checked or other_text:
                joined = ", ".join(items_checked)
                if other_text:
                    joined = f"{joined} (기타: {other_text})" if joined else f"기타: {other_text}"
                section_summaries.append({
                    "section": sec["title"],
                    "count": count,
                    "items": items_checked,
                    "other": other_text,
                    "summary_text": f"{sec['title']}: {joined}"
                })
                # 주요 위험 증상 하이라이트
                for item in items_checked:
                    if any(k in item for k in ["욕하기", "외설적인", "숨이", "가슴이 두근", "잠이 잘 들지", "피가 보인다", "불안"]):
                        alerts.append({
                            "item_no": sec["title"],
                            "question": item,
                            "score": "체크됨",
                            "label": "핵심주의",
                            "is_critical": True
                        })

        severity = "정상"
        color = "#10b981"
        for c in spec.get("cutoffs", []):
            if c["min"] <= total_checked <= c["max"]:
                severity = c["level"]
                color = c["color"]
                break

        return {
            "survey_code": survey_code,
            "title": spec["title"],
            "short_title": spec["short_title"],
            "is_checklist": True,
            "total_score": total_checked,
            "max_score": spec["max_score"],
            "severity": f"{severity} (체크 {total_checked}개)",
            "color": color,
            "alerts": alerts,
            "section_summaries": section_summaries,
            "meta_answers": meta_answers or {},
            "answers": checked_sections,
        }

    # 일반 리커트 척도형 및 YGTSS
    ans_list: List[int] = [int(x) if x is not None else 0 for x in (answers if isinstance(answers, list) else [])]
    questions = spec.get("questions", [])

    if spec.get("is_ygtss"):
        # 운동틱 (0~4번 문항, 0~25점) + 음성틱 (5~9번 문항, 0~25점) + 틱장애척도 (10번 문항, 0~50점)
        motor_score = sum(ans_list[0:5]) if len(ans_list) >= 5 else sum(ans_list)
        vocal_score = sum(ans_list[5:10]) if len(ans_list) >= 10 else 0
        impairment_score = ans_list[10] if len(ans_list) >= 11 else 0
        global_impression = ans_list[11] if len(ans_list) >= 12 else 0
        total_tic_severity = motor_score + vocal_score  # 0~50
        total_score = total_tic_severity + impairment_score  # 0~100
        subscale_info = {
            "운동틱 점수": f"{motor_score}/25점",
            "음성틱 점수": f"{vocal_score}/25점",
            "총 틱증상 점수(운동+음성)": f"{total_tic_severity}/50점",
            "틱장애척도(괴로움)": f"{impairment_score}/50점",
            "전반적인 인상": f"{global_impression}/6점",
        }
    else:
        total_score = sum(ans_list)
        subscale_info = {}
        if "subscales" in spec:
            for _, sub in spec["subscales"].items():
                sub_sum = sum(ans_list[i] for i in sub["indices"] if i < len(ans_list))
                subscale_info[sub["name"]] = f"{sub_sum}/{sub['max']}점"

    # 중증도 판정
    severity = "미분류"
    color = "#10b981"
    for c in spec.get("cutoffs", []):
        if c["min"] <= total_score <= c["max"]:
            severity = c["level"]
            color = c["color"]
            break

    # 주의 문항 추출 (2점 이상 또는 critical_items 해당 문항)
    alerts = []
    threshold = spec.get("alert_threshold", 2)
    critical_set = set(spec.get("critical_items", []))

    for idx, score in enumerate(ans_list):
        item_no = idx + 1
        q_text = questions[idx] if idx < len(questions) else f"문항 {item_no}"
        opts = spec.get("custom_options_by_index", {}).get(idx, spec.get("options", []))
        opt_label = next((o["label"] for o in opts if o["value"] == score), f"{score}점")

        # PHQ-9 9번 문항(자살/자해 사고)은 1점 이상만 되어도 즉시 최우선 경보
        if survey_code == "PHQ9" and item_no == 9 and score >= 1:
            alerts.append({
                "item_no": item_no,
                "question": q_text,
                "score": score,
                "label": opt_label,
                "is_critical": True,
                "alert_note": "🚨 자살/자해 사고 위험 문항 양성 (즉시 임상 면담 필요)"
            })
        elif score >= threshold or (item_no in critical_set and score >= 2):
            alerts.append({
                "item_no": item_no,
                "question": q_text,
                "score": score,
                "label": opt_label,
                "is_critical": item_no in critical_set,
                "alert_note": "핵심 주의 증상" if item_no in critical_set else f"{threshold}점 이상 체크"
            })

    return {
        "survey_code": survey_code,
        "title": spec["title"],
        "short_title": spec["short_title"],
        "is_checklist": False,
        "total_score": total_score,
        "max_score": spec["max_score"],
        "severity": severity,
        "color": color,
        "subscales": subscale_info,
        "alerts": alerts,
        "answers": ans_list,
    }

