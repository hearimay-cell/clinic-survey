-- ============================================================================
-- [해아림한의원 무상태(Stateless) 설문 중계 시스템] Supabase 테이블 & RLS 설정 SQL
-- 테이블명: survey_responses
-- 컬럼 구조: id(자동증가), created_at(시간), chart_id(차트번호 텍스트),
--           survey_type(설문종류 텍스트), scores(채점결과 jsonb), raw_answers(문항응답배열 jsonb)
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.survey_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    chart_id TEXT NOT NULL,                  -- 차트번호 (예: "10293")
    survey_type TEXT NOT NULL,               -- 설문종류 텍스트 (예: "BAI,PHQ9,ISI")
    scores JSONB NOT NULL,                   -- 채점결과 JSONB (총점, 중증도, 주의문항 등)
    raw_answers JSONB NOT NULL               -- 문항응답배열 JSONB
);

CREATE INDEX IF NOT EXISTS idx_survey_responses_created_at ON public.survey_responses (created_at ASC);
CREATE INDEX IF NOT EXISTS idx_survey_responses_chart_id ON public.survey_responses (chart_id);

-- RLS (Row Level Security) 활성화 및 테이블/시퀀스 기본 권한(GRANT) 부여
ALTER TABLE public.survey_responses ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT, INSERT, DELETE ON TABLE public.survey_responses TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

DROP POLICY IF EXISTS "Allow anon insert survey_responses" ON public.survey_responses;
DROP POLICY IF EXISTS "Allow anon select survey_responses" ON public.survey_responses;
DROP POLICY IF EXISTS "Allow anon delete survey_responses" ON public.survey_responses;

-- 1) 환자 모바일 웹: 설문 결과 제출(INSERT) 허용
CREATE POLICY "Allow anon insert survey_responses"
ON public.survey_responses
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- 2) 원내 진료실 PC: 대기 중인 설문 수령(SELECT) 및 7일 일시정지 방지 Ping 조회 허용
CREATE POLICY "Allow anon select survey_responses"
ON public.survey_responses
FOR SELECT
TO anon, authenticated
USING (true);

-- 3) 원내 진료실 PC: 로컬 저장 직후 클라우드 원본 즉시 휘발 삭제(DELETE) 허용
CREATE POLICY "Allow anon delete survey_responses"
ON public.survey_responses
FOR DELETE
TO anon, authenticated
USING (true);
